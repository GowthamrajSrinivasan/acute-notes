/** The generated validation and coverage report (`reports/validation-report.md`). Counts come from the files, never typed in. */
import type { Dataset } from "./load";
import { ELEMENT_TYPES, GATE_OF_DIMENSION, RUBRIC_DIMENSIONS } from "./schemas";

function tally<T extends string>(values: readonly T[]): Map<T, number> {
  const m = new Map<T, number>();
  for (const v of values) m.set(v, (m.get(v) ?? 0) + 1);
  return m;
}

function table(head: string[], rows: (string | number)[][]): string {
  return [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
}

const STATUS_ORDER = ["implemented", "partially_implemented", "planned", "not_found", "needs_verification"] as const;

/** `reports/capability-inventory.md`, from `capabilities.json` (the same data the validator checks assertions against). */
export function buildInventory(d: Dataset): string {
  const out: string[] = ["# Capability inventory", ""];
  out.push(`Inspected ${d.capabilities.inspectedAt} against the code, not the plans. Generated from \`capabilities.json\` by \`UPDATE_GOLDEN=1 npm run test:golden\`; edit the JSON, not this file.`, "");
  out.push("Status meanings: **implemented** = confirmed in the code; **partially_implemented** = exists but doesn't fully support the intended behaviour; **planned** = described in a plan, not in the code; **not_found** = no supporting code; **needs_verification** = the evidence is inconclusive.", "");
  const used = new Map<string, string[]>();
  for (const c of d.cases) for (const id of new Set([...c.source.capabilities, ...c.evaluation.assertions.flatMap((a) => a.requires ?? [])])) used.set(id, [...(used.get(id) ?? []), c.id.slice(0, 5)]);
  for (const status of STATUS_ORDER) {
    const caps = d.capabilities.capabilities.filter((c) => c.status === status);
    if (!caps.length) continue;
    out.push(`## ${status} (${caps.length})`, "");
    out.push(table(["Capability", "Area", "What the code does", "Evidence", "Cases"], caps.map((c) => [`\`${c.id}\``, c.category, c.summary.replace(/\|/g, "\\|"), c.evidence.map((e) => `\`${e}\``).join("<br>"), (used.get(c.id) ?? []).join(", ") || "–"])), "");
  }
  return `${out.join("\n")}\n`;
}

export function buildReport(d: Dataset, problems: readonly string[]): string {
  const cases = d.cases;
  const assertions = cases.flatMap((c) => c.evaluation.assertions.map((a) => ({ ...a, caseId: c.id })));
  const det = assertions.filter((a) => a.method === "deterministic");
  const out: string[] = [];
  out.push("# Validation and coverage report", "");
  out.push("Generated by `UPDATE_GOLDEN=1 npm run test:golden` from the dataset files. Do not edit by hand.", "");
  out.push(`Dataset version ${d.manifest.datasetVersion}. Validation problems: **${problems.length}**.`, "");
  if (problems.length) out.push(...problems.map((p) => `- ${p}`), "");

  out.push("## Cases", "");
  out.push(
    table(
      ["Case", "Source type", "Words", "Units (critical)", "Knowledge", "Frames", "Elements", "Relationships", "Lens", "Assertions (deterministic)", "Review"],
      cases.map((c) => [
        c.id,
        c.source.sourceType,
        c.source.sourceFiles.map((f) => f.words).join(" → "),
        `${c.source.units.length} (${c.source.units.filter((u) => u.critical).length})`,
        c.knowledge.units.length,
        c.canvas.frames.length,
        c.canvas.elements.length,
        c.canvas.relationships.length,
        c.lens ? c.lens.levels.filter((l) => l.availability !== "unavailable").map((l) => `L${l.level}`).join(" ") : "–",
        `${c.evaluation.assertions.length} (${c.evaluation.assertions.filter((a) => a.method === "deterministic").length})`,
        c.source.review.status,
      ]),
    ),
    "",
  );

  out.push("## Element types covered", "");
  const elements = cases.flatMap((c) => c.canvas.elements);
  out.push(
    table(
      ["Element", "Expected elements", "Cases", "Support today"],
      ELEMENT_TYPES.map((t) => {
        const es = elements.filter((e) => e.element === t);
        const inCases = cases.filter((c) => c.canvas.elements.some((e) => e.element === t)).length;
        return [t, es.length, inCases, [...tally(es.map((e) => e.support)).entries()].map(([s, n]) => `${s} ${n}`).join(", ") || "–"];
      }),
    ),
    "",
  );
  const relTypes = tally(cases.flatMap((c) => c.canvas.relationships.map((r) => r.type)));
  out.push(`Relationship types used: ${[...relTypes.entries()].map(([t, n]) => `\`${t}\` ${n}`).join(", ")}.`, "");
  out.push(`Frames: ${cases.reduce((n, c) => n + c.canvas.frames.length, 0)} (${cases.reduce((n, c) => n + c.canvas.frames.filter((f) => f.diagram).length, 0)} architecture diagram frames).`, "");

  out.push("## Lens levels covered", "");
  const lensCases = cases.filter((c) => c.lens);
  out.push(
    table(
      ["Case", ...[0, 1, 2, 3, 4, 5].map((l) => `L${l}`)],
      lensCases.map((c) => [c.id, ...[0, 1, 2, 3, 4, 5].map((l) => c.lens!.levels.filter((x) => x.level === l).map((x) => x.availability).join("/") || "–")]),
    ),
    "",
  );

  out.push("## Assertions", "");
  out.push(`${assertions.length} assertions: ${det.length} deterministic, ${assertions.length - det.length} judged (model or human).`, "");
  out.push(
    table(
      ["Dimension", "Gate", "Deterministic (runs today)", "Deterministic (future)", "Model judge", "Human"],
      RUBRIC_DIMENSIONS.map((dim) => {
        const mine = assertions.filter((a) => a.dimension === dim);
        return [dim, GATE_OF_DIMENSION[dim], mine.filter((a) => a.method === "deterministic" && a.support !== "future").length, mine.filter((a) => a.method === "deterministic" && a.support === "future").length, mine.filter((a) => a.method === "model_judge").length, mine.filter((a) => a.method === "human").length];
      }),
    ),
    "",
  );
  const checks = tally(det.flatMap((a) => (a.check ? [a.check.check] : [])));
  out.push(`Deterministic checks by kind: ${[...checks.entries()].map(([k, n]) => `\`${k}\` ${n}`).join(", ")}.`, "");

  out.push("## Regression cases", "");
  out.push(table(["Regression", "Distortion", "Case", "Target", "Must fail"], d.regressions.map((r) => [r.id, r.distortion, r.caseId, r.target, r.expectFailing.join(", ")])), "");

  out.push("## Capability inventory", "");
  out.push(table(["Status", "Count"], [...tally(d.capabilities.capabilities.map((c) => c.status)).entries()].map(([s, n]) => [s, n])), "");
  return `${out.join("\n")}\n`;
}
